fn main() {
    let no_1 =10;
    let no_2=2;
    let mut result:i32;

    result = no_1 + no_2;
    println!("\nSum : {}",result);

    result = no_1 - no_2;
    println!("\nDifference : {} ", result);

    result = no_1*no_2;
    println!("\nProduct: {}", result);

    result = no_1/no_2;
    println!("\nQuotient ; {} ", result);

    result = no_1%no_2;
    println!("\nRemainder : {}",result);

}
